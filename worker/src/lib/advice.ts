// ---------------------------------------------------------------------------
// Phase 5 — Hybrid advice engine: deterministic CPCB NAQI + profile-sensitivity
// rules, with a Cloudflare Workers AI layer (llama-3.1-8b-instruct-fast primary,
// llama-3.3-70b-instruct-fp8-fast secondary) that rephrases and contextualises
// the deterministic result. The deterministic
// rules are always computed; the AI output is validated against them and
// discarded (fallback) when the binding is missing, times out, or returns
// unparseable content. PRD guardrails hold: advice is grounded strictly in
// the caller-supplied live NAQI/pollutant readings — the model never sees
// enough room to invent measurements, and null readings are reported as
// "data unavailable", never substituted with zero.
// ---------------------------------------------------------------------------

// Minimal inline worker-AI type placeholders — the @cloudflare/workers-types
// version pinned for this project does not yet expose the experimental Ai*
// members in this release. Define locally so tsc --noEmit does not error.
interface AiMessage {
  role: string;
  content?: string | null;
}
interface AiResponse {
  response: string;
}

// AI binding type from the project's bindings.d.ts (generated by wrangler types):
// export interface Ai { run<T = any>(model: string, opts: { raw?: true; messages: AiMessage[] }): Promise<AiResponse>; }

export interface AdviceProfileInput {
  name: string;
  age: number;
  lifestyle: string;
  health_conditions: string[];
  has_air_purifier: boolean;
  uses_n95_mask: boolean;
  ventilates_windows: boolean;
}

export interface AdviceStopInput {
  label: string;
  /** Live NAQI for this stop's own location, or null when unavailable. */
  naqi: number | null;
  usAqi?: number | null;
  categoryLabel?: string;
  hours?: number;
  environmentType?: string;
}

export interface AdviceRequest {
  profile: AdviceProfileInput | null;
  stops: AdviceStopInput[];
  /** 0–100 Personal Exposure Score from the deterministic frontend engine. */
  exposureScore: number | null;
  departureTime?: string; // "HH:MM"
  transitMode?: string;
}

export type AdviceTipKind = "departure" | "transit" | "mask" | "purifier" | "activity" | "general";

export interface AdviceTip {
  kind: AdviceTipKind;
  text: string;
  /** The deterministic rule id that produced the tip (audit + fallback parity). */
  rule: string;
}

export interface AdviceOutcome {
  source: "ai" | "rules-fallback";
  /** Set only when the AI path was attempted and degraded. */
  ai_error?: string;
  summary: string;
  tips: AdviceTip[];
  exposure_score: number | null;
  generated_at: string;
}

// ---------------------------------------------------------------------------
// Deterministic rule engine
// ---------------------------------------------------------------------------

const RESPIRATORY_RX = /asthma|copd|respir|lung|bronch/i;
const CARDIO_RX = /heart|cardio|hypertension|diabetes|coronary/i;

/** Indian commuter rush windows (local time) when roadside NO2/PM peaks. */
function isRushHour(timeHHMM: string | undefined): boolean {
  if (!timeHHMM) return false;
  const m = /^([01]?\d|2[0-3]):[0-5]\d$/.exec(timeHHMM);
  if (!m) return false;
  const mins = parseInt(m[1], 10) * 60 + parseInt(timeHHMM.slice(3), 10);
  const amPeak = mins >= 7 * 60 && mins <= 9 * 60 + 30; // 07:00–09:30
  const pmPeak = mins >= 17 * 60 && mins <= 20 * 60; // 17:00–20:00
  return amPeak || pmPeak;
}

function exposureBand(score: number | null): string {
  if (score === null) return "unavailable";
  if (score < 40) return "low";
  if (score < 70) return "moderate";
  if (score < 90) return "high";
  return "very high";
}

export interface DeterministicAdvice {
  summary: string;
  tips: AdviceTip[];
  /** Compact context handed to the AI layer (also the audit trail). */
  context: Record<string, unknown>;
}

export function deterministicAdvice(req: AdviceRequest): DeterministicAdvice {
  const stops = req.stops;
  const profile = req.profile;
  const withData = stops.filter((s) => s.naqi !== null && s.naqi !== undefined);
  const worst = withData.reduce<AdviceStopInput | null>(
    (acc, s) => (acc === null || (s.naqi ?? 0) > (acc.naqi ?? 0) ? s : acc),
    null,
  );
  const tips: AdviceTip[] = [];

  // R1 — data availability (never substitute zeros).
  if (withData.length === 0) {
    tips.push({
      kind: "general",
      rule: "no-data",
      text: "No live air-quality readings were available for this route — tips below rely on the profile and routine only. Retry the AQI check in a few minutes.",
    });
  }

  // R2 — category-based protective actions at the worst stop.
  const w = worst?.naqi ?? null;
  if (w !== null) {
    if (w <= 50) {
      tips.push({ kind: "general", rule: "naqi-good", text: `Air at ${worst!.label} is Good (NAQI ${w}) — no protective gear needed; a normal day outdoors is fine.` });
    } else if (w <= 100) {
      tips.push({ kind: "activity", rule: "naqi-moderate", text: `Air is Satisfactory (NAQI ${w}). ${profile ? `${profile.name} may ` : "You may "}limit heavy outdoor exertion to brief bursts.` });
    } else if (w <= 200) {
      tips.push({ kind: "activity", rule: "naqi-poor", text: `Air at ${worst!.label} is Poor–Unhealthy (NAQI ${w}) — keep outdoor time at ${worst!.label} short and plan breaks indoors.` });
    } else if (w <= 300) {
      tips.push({ kind: "activity", rule: "naqi-unhealthy-sensitive", text: `${worst!.label} is Unhealthy for sensitive groups (NAQI ${w}) — limit prolonged outdoor activity and keep the routine efficient.` });
    } else {
      tips.push({ kind: "activity", rule: "naqi-severe", text: `${worst!.label} is Severe (NAQI ${w}) — carry an N95 and keep every outdoor segment as brief as possible; defer anything non-essential.` });
    }
  }

  // R3 — departure timing vs. rush-hour pollutant peaks.
  if (worst && w !== null && w > 100 && isRushHour(req.departureTime)) {
    tips.push({
      kind: "departure",
      rule: "rush-hour",
      text: `Departure at ${req.departureTime} lands in a rush-hour window when roadside PM/NO2 peaks at ${worst.label} — if you can, shift the leg later or earlier in the day.`,
    });
  }

  // R4 — transit swaps that cut inhaled dose (roadside vs sealed).
  const openModes = ["two_wheeler", "auto_non_ac", "walk"];
  if (worst && w !== null && w >= 100 && openModes.includes(req.transitMode ?? "")) {
    tips.push({
      kind: "transit",
      rule: "transit-swap",
      text: `Switching the ${req.transitMode} leg to Metro/Bus or a Car-with-AC cuts roadside inhaled dose by roughly 50–60% on this route.`,
    });
  }

  // R5 — N95 recommendation / reminder, scaled to the worst reading.
  if (w !== null && w >= 150) {
    tips.push(
      profile?.uses_n95_mask
        ? { kind: "mask", rule: "mask-reminder", text: `NAQI ${w} at ${worst!.label} — remember ${profile.name}'s N95 for the outdoor leg; a well-fitted mask cuts PM2.5 inhaled dose substantially.` }
        : { kind: "mask", rule: "mask-suggest", text: `NAQI ${w} at ${worst!.label} — a well-fitted N95 is recommended for the outdoor segments of this routine.` },
    );
  }

  // R6 — HEPA purifier action for home/incoming segments.
  if ((w !== null && w >= 150) || (req.exposureScore !== null && req.exposureScore >= 70)) {
    if (profile?.has_air_purifier) {
      tips.push({ kind: "purifier", rule: "purifier-run", text: "Turn on the HEPA air purifier before arriving home — it will scrub the PM2.5 the routine picked up." });
    } else {
      tips.push({ kind: "purifier", rule: "purifier-suggest", text: "No air purifier on file — a HEPA purifier would cut indoor PM2.5 carried in from this routine." });
    }
  }

  // R7 — sensitivity flags (age + health conditions).
  const conds = (profile?.health_conditions ?? []).join(", ");
  if (profile && w !== null && w >= 101) {
    if (profile.age <= 12 || RESPIRATORY_RX.test(conds)) {
      tips.push({ kind: "general", rule: "sensitive-child-respiratory", text: `${profile.name} is a flagged sensitive group (child/respiratory) — on days like today, indoor time and N95 outdoors take priority.` });
    } else if (profile.age >= 65 || CARDIO_RX.test(conds)) {
      tips.push({ kind: "general", rule: "sensitive-senior-cardio", text: `${profile.name} is a flagged sensitive group (senior/cardiovascular) — avoid the ${worst!.label} leg if the reading rises further.` });
    }
  }

  // R8 — exposure score band framing.
  const band = exposureBand(req.exposureScore);
  let summary: string;
  if (withData.length === 0) {
    summary = "Live air-quality data was unavailable for this routine, so these tips are based on the profile's sensitivity and habits only.";
  } else if (band === "low") {
    summary = `Routine exposure is LOW (score ${req.exposureScore}). Air is acceptable at every stop with data — keep the routine as planned and stay aware of the ${worst!.label} stop (NAQI ${worst!.naqi}).`;
  } else if (band === "moderate") {
    summary = `Routine exposure is MODERATE (score ${req.exposureScore}). The ${worst!.label} stop (NAQI ${worst!.naqi}) drives most of the dose — apply the protective tips below for that segment.`;
  } else {
    summary = `Routine exposure is ${band.toUpperCase()} (score ${req.exposureScore}). The ${worst!.label} stop (NAQI ${worst!.naqi}) dominates the inhaled dose — use the protective tips below for today's route.`;
  }

  const context = {
    profile: profile
      ? { name: profile.name, age: profile.age, lifestyle: profile.lifestyle, health_conditions: profile.health_conditions, has_air_purifier: profile.has_air_purifier, uses_n95_mask: profile.uses_n95_mask }
      : null,
    stops: stops.map((s) => ({ label: s.label, naqi: s.naqi, usAqi: s.usAqi ?? null, category: s.categoryLabel ?? null })),
    exposure_score: req.exposureScore,
    exposure_band: band,
    transit_mode: req.transitMode ?? null,
    departure_time: req.departureTime ?? null,
    deterministic_tips: tips,
  };

  return { summary, tips, context };
}

// ---------------------------------------------------------------------------
// Workers AI layer with hard timeout + fallback (primary model first, then
// secondary, then deterministic rules)
// ---------------------------------------------------------------------------

const AI_MODEL = "@cf/meta/llama-3.1-8b-instruct-fast";
const AI_MODEL_FALLBACK = "@cf/meta/llama-3.3-70b-instruct-fp8-fast";
const AI_TIMEOUT_MS = 30_000;
const TIP_KINDS: readonly string[] = ["departure", "transit", "mask", "purifier", "activity", "general"];

function aiMessages(det: DeterministicAdvice, req: AdviceRequest): AiMessage[] {
  const system =
    "You are AirAware's routine health advisor. Write short, practical advice for one person's daily routine in Indian cities. " +
    "Ground every claim strictly in the provided JSON: use the NAQI numbers exactly as given, never invent readings, stations, forecasts or weather. " +
    "Treat null naqi values as unavailable data and say so. Keep advice concrete (departure timing, transit swaps, N95 mask, HEPA purifier, activity limits).";
  const user =
    JSON.stringify({ request: { departure_time: req.departureTime, transit_mode: req.transitMode }, data: det.context }) +
    "\nRespond with STRICT JSON only (no markdown): {\"summary\": string (50–80 words), \"tips\": [{\"kind\": \"departure\"|\"transit\"|\"mask\"|\"purifier\"|\"activity\"|\"general\", \"text\": string (max 25 words)}]}. Return at most 4 tips, consistent with the deterministic tips provided.";
  return [
    { role: "system", content: system },
    { role: "user", content: user },
  ];
}

function extractJson(text: string): { summary?: string; tips?: Array<{ kind?: unknown; text?: unknown }> } | null {
  // Llama occasionally wraps JSON in a code fence; strip it.
  const cleaned = text.replace(/```(?:json)?/gi, "").trim();
  const start = cleaned.indexOf("{");
  const end = cleaned.lastIndexOf("}");
  if (start === -1 || end <= start) return null;
  try {
    return JSON.parse(cleaned.slice(start, end + 1)) as { summary?: string; tips?: Array<{ kind?: unknown; text?: unknown }> };
  } catch {
    return null;
  }
}

/**
 * Build the hybrid advice response. The deterministic engine always runs;
 * the AI call is a bounded overlay. Any failure (unbound, timeout, unparsable
 * output, off-schema kinds) degrades to the deterministic result — the PRD
 * hybrid-fallback guardrail.
 */
export async function buildAdvice(req: AdviceRequest, ai: Ai | undefined): Promise<AdviceOutcome> {
  const det = deterministicAdvice(req);
  const base: AdviceOutcome = {
    source: "rules-fallback",
    summary: det.summary,
    tips: det.tips,
    exposure_score: req.exposureScore,
    generated_at: new Date().toISOString(),
  };

  if (!ai) {
    base.ai_error = "AI binding unbound";
    console.warn("[advice] AI binding unbound — degrading to rules fallback");
    return base;
  }

  // Try primary model first, then fallback model, then deterministic rules
  const modelSequence: string[] = [AI_MODEL, AI_MODEL_FALLBACK];
  let lastError: string | undefined;

  for (const model of modelSequence) {
    try {
      const aiAttempt = (async () => {
        const race: Promise<AiResponse | { timedOut: true }> = ai.run(model, {
          raw: true,
          messages: aiMessages(det, req),
          temperature: 0.3,
          max_tokens: 700,
        }) as Promise<AiResponse | { timedOut: true }>;
        const timeout = new Promise<{ timedOut: true }>((resolve) => setTimeout(() => resolve({ timedOut: true }), AI_TIMEOUT_MS));
        const rawRes = await Promise.race([race, timeout]);
        if ("timedOut" in rawRes) throw new Error(`AI timeout after ${AI_TIMEOUT_MS}ms`);
        if (typeof rawRes.response !== "string") throw new Error("AI returned no text payload");
        const parsed = extractJson(rawRes.response);
        if (!parsed || typeof parsed.summary !== "string" || !Array.isArray(parsed.tips)) {
          throw new Error("AI output was not valid advice JSON");
        }
        const tips: AdviceTip[] = parsed.tips
          .filter((t) => typeof t?.text === "string" && t.text.length > 0)
          .filter((t) => typeof t?.kind === "string" && TIP_KINDS.includes(t.kind as string))
          .slice(0, 4)
          .map((t) => ({ kind: t.kind as AdviceTipKind, text: t.text as string, rule: "ai" }));
        return { summary: parsed.summary.trim(), tips };
      })();

      const aiOut = await aiAttempt;
      return {
        ...base,
        source: "ai",
        summary: aiOut.summary,
        tips: aiOut.tips.length > 0 ? [...aiOut.tips, ...det.tips] : det.tips,
      };
    } catch (err) {
      lastError = err instanceof Error ? err.message : String(err);
      console.warn(`[advice] AI model ${model} failed: ${lastError}`);
      // Continue to next model in sequence
      continue;
    }
  }

  // All models failed — degrade to deterministic rules
  base.ai_error = lastError || "AI model failed";
  console.warn(`[advice] all AI models failed — degrading to rules fallback (${base.ai_error})`);
  return base;
}
